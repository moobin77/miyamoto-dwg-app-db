// Combine core drawings with all auto-generated drawings for remaining length variants in SAS, PTS, and OTS
export function generateAllInitialDrawings(): Drawing[] {
  const result: Drawing[] = [...CORE_INITIAL_DRAWINGS];
  const existingDrawingIds = new Set(result.map((d) => d.id));

  for (const dept of INITIAL_DEPARTMENTS) {
    for (const model of dept.models) {
      for (const len of model.lengths) {
        if (!existingDrawingIds.has(len.drawingId)) {
          const newDwg = createDrawingForLength(dept.id, model, len);
          result.push(newDwg);
          existingDrawingIds.add(len.drawingId);
        }
      }
    }
  }

  return result;
}

export const INITIAL_DRAWINGS: Drawing[] = generateAllInitialDrawings();
